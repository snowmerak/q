import { test, expect } from '@playwright/test';

test('Composer expands previews and supports readable D2 zoom and pan', async ({ page, request }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const created = await request.post('/api/v1/composers', { data: { name: 'Large diagram idea', model: 'default/test-model' } });
  const { id } = await created.json();
  const base = `/api/v1/composers/${id}/artifacts/source?path=`;
  try {
    const diagram = 'direction: right\n' + Array.from({ length: 14 }, (_, index) => `step_${index}: Step ${index}`).join('\n') + '\n' + Array.from({ length: 14 }, (_, index) => `step_${index}`).join(' -> ');
    expect((await request.put(base + encodeURIComponent('docs/diagram/large.d2'), { data: { content: diagram, expected_hash: '' } })).ok()).toBe(true);
    expect((await request.put(base + encodeURIComponent('docs/webcomponent/demo.html'), { data: { content: '<!doctype html><h1>Expanded component</h1><button onclick="this.textContent=\'Working\'">Try it</button><p id="isolation"></p><script>try { parent.document.body; } catch { document.querySelector(\'#isolation\').textContent=\'Isolated\'; }</script>', expected_hash: '' } })).ok()).toBe(true);
    await page.goto(`/composers/${id}`);
    await expect(page).toHaveTitle('Composer · Q Studio');
    const artifacts = page.getByRole('region', { name: 'Composer artifacts' });
    const preview = page.frameLocator('iframe[title="Artifact preview"]');
    const svg = preview.locator('#diagram > svg');
    await expect(svg).toBeVisible();
    const natural = await svg.boundingBox();
    expect(natural.width).toBeGreaterThan(1500);
    await preview.getByRole('button', { name: 'Zoom in', exact: true }).click();
    await expect(preview.locator('#scale')).toHaveText('125%');
    expect((await svg.boundingBox()).width).toBeCloseTo(natural.width * 1.25, 0);
    await preview.getByRole('button', { name: 'Zoom out', exact: true }).click();
    await expect(preview.locator('#scale')).toHaveText('100%');
    await preview.getByRole('button', { name: 'Fit', exact: true }).click();
    const viewport = await preview.getByRole('region', { name: 'Diagram canvas' }).boundingBox();
    expect((await svg.boundingBox()).width).toBeLessThanOrEqual(viewport.width);
    const fitted = await preview.locator('#scale').textContent();
    await preview.getByRole('region', { name: 'Diagram canvas' }).hover();
    await page.mouse.wheel(0, -150);
    await expect(preview.locator('#scale')).not.toHaveText(fitted);
    await preview.getByRole('button', { name: 'Actual size (100%)', exact: true }).click();
    const before = await svg.boundingBox();
    await page.mouse.move(viewport.x + 150, viewport.y + 100);
    await page.mouse.down();
    await page.mouse.move(viewport.x + 230, viewport.y + 145, { steps: 5 });
    await page.mouse.up();
    const after = await svg.boundingBox();
    expect(after.x - before.x).toBeCloseTo(80, 0);
    expect(after.y - before.y).toBeCloseTo(45, 0);
    await artifacts.getByRole('button', { name: 'Expand preview', exact: true }).click();
    const expanded = page.getByRole('dialog', { name: 'Artifact preview', exact: true });
    await expect(expanded).toBeVisible();
    const expandedFrame = page.frameLocator('iframe[title="Expanded artifact preview"]');
    await expect(expandedFrame.locator('#diagram > svg')).toBeVisible();
    expect((await expanded.boundingBox()).width).toBeGreaterThan(1300);
    expect((await expandedFrame.locator('#diagram text').first().boundingBox()).height).toBeGreaterThanOrEqual(12);
    await page.screenshot({ path: testInfo.outputPath('expanded-d2-actual-size.png'), fullPage: false });
    await expandedFrame.getByRole('button', { name: 'Fit', exact: true }).click();
    await expandedFrame.getByRole('region', { name: 'Diagram canvas' }).click();
    await page.screenshot({ path: testInfo.outputPath('expanded-d2.png'), fullPage: false });
    await page.keyboard.press('Escape');
    await expect(expanded).not.toBeVisible();
    await expect(artifacts.getByRole('button', { name: 'Expand preview', exact: true })).toBeFocused();
    await artifacts.getByLabel('File', { exact: true }).selectOption('docs/webcomponent/demo.html');
    await artifacts.getByRole('button', { name: 'Expand preview', exact: true }).click();
    await expect(expandedFrame.getByRole('heading', { name: 'Expanded component' })).toBeVisible();
    await expandedFrame.getByRole('button', { name: 'Try it' }).click();
    await expect(expandedFrame.getByRole('button', { name: 'Working', exact: true })).toBeVisible();
    await expect(expandedFrame.getByText('Isolated', { exact: true })).toBeVisible();
    await expanded.getByRole('button', { name: 'Close expanded preview' }).click();
    await page.setViewportSize({ width: 760, height: 900 });
    await artifacts.getByLabel('File', { exact: true }).selectOption('docs/diagram/large.d2');
    await artifacts.getByRole('button', { name: 'Expand preview', exact: true }).click();
    await expect(expandedFrame.locator('#diagram > svg')).toBeVisible();
    expect((await expanded.boundingBox()).width).toBeLessThanOrEqual(760);
    await page.screenshot({ path: testInfo.outputPath('expanded-d2-mobile-actual-size.png'), fullPage: false });
    await expandedFrame.getByRole('button', { name: 'Fit', exact: true }).click();
    await page.screenshot({ path: testInfo.outputPath('expanded-d2-mobile.png'), fullPage: false });
    await expanded.getByRole('button', { name: 'Close expanded preview' }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(errors).toEqual([]);
  } finally { await request.delete(`/api/v1/composers/${id}`); }
});

test('Composer refines artifacts through questions, source editing, and isolated previews', async ({ page, request }, testInfo) => {
  const created = await request.post('/api/v1/composers', { data: { name: 'Visual reading idea', model: 'default/test-model' } });
  const { id } = await created.json();
  const base = `/api/v1/composers/${id}`;
  try {
    await page.goto(`/composers/${id}`);
    await page.getByLabel('Develop your idea').fill('composer artifacts');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Which view should we develop?' })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Which view should we develop?' })).toBeVisible();
    await page.getByRole('button', { name: /Reading flow Draw the reader journey/ }).click();
    await expect(page.getByText('Created the reading flow and an interactive club component.', { exact: false })).toBeVisible();
    const artifacts = page.getByRole('region', { name: 'Composer artifacts' });
    await expect(artifacts.getByLabel('File', { exact: true }).locator('option')).toHaveCount(2);
    const preview = page.frameLocator('iframe[title="Artifact preview"]');
    await expect(preview.locator('svg').first()).toBeVisible();
    await artifacts.getByLabel('File', { exact: true }).selectOption('docs/webcomponent/reading.html');
    await expect(preview.getByRole('heading', { name: 'Reading club' })).toBeVisible();
    await preview.getByRole('button', { name: 'Join club' }).click();
    await expect(preview.getByRole('button', { name: 'Joined!' })).toBeVisible();
    await artifacts.getByRole('button', { name: 'Source', exact: true }).click();
    const editor = artifacts.getByLabel('Artifact source');
    await editor.fill('<!doctype html><h1>Refined idea</h1><button onclick="this.textContent=\'Done\'">Try refinement</button><p id="isolation"></p><script>try { parent.document.body; document.querySelector(\'#isolation\').textContent=\'unsafe\'; } catch { document.querySelector(\'#isolation\').textContent=\'Isolated\'; }</script>');
    await artifacts.getByRole('button', { name: 'Save source' }).click();
    await expect(artifacts.getByText('All changes saved', { exact: true })).toBeVisible();
    await artifacts.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect(preview.getByRole('heading', { name: 'Refined idea' })).toBeVisible();
    await expect(preview.getByText('Isolated', { exact: true })).toBeVisible();
    await preview.getByRole('button', { name: 'Try refinement' }).click();
    await expect(preview.getByRole('button', { name: 'Done', exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('composer-artifacts.png'), fullPage: true });
    await artifacts.getByLabel('File', { exact: true }).selectOption('docs/diagram/reading.d2');
    await artifacts.getByRole('button', { name: 'Source', exact: true }).click();
    await editor.fill('a: {');
    await artifacts.getByRole('button', { name: 'Save source' }).click();
    await expect(artifacts.getByText('All changes saved', { exact: true })).toBeVisible();
    await artifacts.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect(preview.getByRole('heading', { name: 'Preview unavailable' })).toBeVisible();
    await artifacts.getByRole('button', { name: 'Source', exact: true }).click();
    await editor.fill('reader -> improved_club');
    await artifacts.getByRole('button', { name: 'Save source' }).click();
    await expect(artifacts.getByText('All changes saved', { exact: true })).toBeVisible();
    await artifacts.getByRole('button', { name: 'Preview', exact: true }).click();
    await expect(preview.locator('svg').first()).toBeVisible();
    await page.setViewportSize({ width: 760, height: 900 });
    await expect(artifacts.getByRole('button', { name: 'New artifact' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    page.once('dialog', dialog => dialog.accept());
    await artifacts.getByRole('button', { name: 'Delete file' }).click();
    await expect(artifacts.getByLabel('File', { exact: true }).locator('option')).toHaveCount(1);
    await artifacts.getByRole('button', { name: 'New artifact' }).click();
    await artifacts.getByLabel('Filename', { exact: true }).fill('new-flow');
    await artifacts.getByRole('button', { name: 'Create artifact' }).click();
    await expect(artifacts.getByLabel('File', { exact: true })).toHaveValue('docs/diagram/new-flow.d2');
    await page.reload();
    const listing = await (await request.get(`${base}/artifacts`)).json();
    expect(listing.artifacts).toHaveLength(2);
  } finally {
    await request.post(`${base}/cancel`, { data: {} });
    await request.delete(base);
  }
});

test('Composer creates a model conversation, saves history, and continues after reload', async ({ page, request }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/v1/settings/models', route => route.fulfill({ json: { models: [
    { id: 'default/test-model' }, { id: 'a-fallback-group', group: true }
  ] } }));
  let id;
  try {
    await page.goto('/');
    await page.getByRole('button', { name: 'Composer', exact: true }).click();
    await expect(page).toHaveTitle('Composer · Q Studio');
    await page.getByRole('button', { name: 'New', exact: true }).click();
    await page.getByLabel('Name', { exact: true }).fill('Reading club idea');
    await expect(page.getByRole('combobox', { name: 'Model', exact: true }).locator('option')).toHaveText(['default/test-model']);
    await page.getByRole('button', { name: 'Create conversation' }).click();
    await expect(page.getByRole('heading', { name: 'Reading club idea', exact: true })).toBeVisible();
    id = new URL(page.url()).pathname.split('/').pop();
    const input = page.getByLabel('Develop your idea');
    await input.fill('I want to make a reading club app');
    await input.press('Enter');
    const history = page.getByRole('region', { name: 'Conversation history' });
    await expect(history.getByText('Who would use your idea first?', { exact: true })).toBeVisible();
    await page.reload();
    await expect(history.getByText('I want to make a reading club app', { exact: true })).toBeVisible();
    await expect(history.getByText('Who would use your idea first?', { exact: true })).toBeVisible();
    await input.fill('The first users are students');
    await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeEnabled();
    await input.press('Shift+Enter');
    await expect(input).toHaveValue('The first users are students\n');
    await input.press('Enter');
    await expect(history.getByText("Let's develop the reading club idea for students.", { exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('conversation.png'), fullPage: true });
    const detail = await (await request.get(`/api/v1/composers/${id}`)).json();
    expect(detail.model).toBe('default/test-model');
    expect(detail.turns).toHaveLength(2);
    expect(detail.turns.every(turn => turn.status === 'completed')).toBe(true);
    await page.getByRole('button', { name: 'Sessions', exact: true }).click();
    await page.getByRole('button', { name: 'Composer', exact: true }).click();
    await page.getByRole('button', { name: /Reading club idea default\/test-model/ }).click();
    await expect(history.getByText("Let's develop the reading club idea for students.", { exact: true })).toBeVisible();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Delete', exact: true }).click();
    await expect(page.getByRole('button', { name: /Reading club idea default\/test-model/ })).toHaveCount(0);
    expect((await request.get(`/api/v1/composers/${id}`)).status()).toBe(404);
    expect(errors).toEqual([]);
  } finally { if (id) await request.delete(`/api/v1/composers/${id}`); }
});

test('Composer survives browser reload during a reply and can stop and continue', async ({ page, request }) => {
  const response = await request.post('/api/v1/composers', { data: { name: 'Explore slowly', model: 'default/test-model' } });
  const conversation = await response.json();
  const id = conversation.id;
  try {
    await page.goto(`/composers/${id}`);
    const input = page.getByLabel('Develop your idea');
    await input.fill('composer wait');
    await input.press('Enter');
    await expect(page.getByRole('button', { name: 'Stop reply' })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('button', { name: 'Stop reply' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Delete', exact: true })).toBeDisabled();
    await page.getByRole('button', { name: 'Stop reply' }).click();
    await expect(page.getByText('Reply stopped. You can continue the conversation.', { exact: true })).toBeVisible();
    await input.fill('I want a reading club for students');
    await input.press('Enter');
    await expect(page.getByText("Let's develop the reading club idea for students.", { exact: true })).toBeVisible();
  } finally {
    await request.post(`/api/v1/composers/${id}/cancel`, { data: {} });
    await request.delete(`/api/v1/composers/${id}`);
  }
});
